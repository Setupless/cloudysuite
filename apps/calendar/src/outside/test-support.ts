// An event whose only odd part is its repeat rule.
export const withRule = (rule: string, uid = "hostile@example.net") =>
  calendarFile(
    "BEGIN:VEVENT",
    `UID:${uid}`,
    "DTSTART;TZID=Australia/Sydney:20260203T090000",
    "DTEND;TZID=Australia/Sydney:20260203T100000",
    `RRULE:${rule}`,
    "SUMMARY:Odd repeat",
    "END:VEVENT",
  );

